// Asset-path and CSS rewriting for the `next` target.
//
// The static target inlines hydration and references assets with page-relative
// URLs (./figures/…). The `next` target is embedded in a host app, so its
// assets live under a single base path (e.g. /gazette, served from
// public/gazette) and are referenced by absolute URL. This module builds
// base-path-absolute URLs and the single shadow-root stylesheet.
import fs from "node:fs";
import path from "node:path";
import { VENDOR } from "../config.js";

// Join a base path and a relative asset path into one absolute URL.
//   joinBase("/gazette", "figures/trend-line.js") -> "/gazette/figures/trend-line.js"
export function joinBase(basePath, rel) {
  const b = String(basePath || "").replace(/\/+$/, "");
  const r = String(rel || "").replace(/^\.?\/+/, "");
  return `${b}/${r}`;
}

// Rewrite gazette's document-level CSS so it applies inside a shadow root:
//   :root / html / body selectors -> :host (a shadow tree has no document root)
// tokens.css and gazette.css otherwise reference only fonts/… URLs, which still
// resolve correctly against the emitted stylesheet's own URL (<base>/fonts/…),
// so @font-face is kept inline and the shadow tree loads its own fonts.
function shadowify(css) {
  return css
    .replace(/(^|[}\n])\s*:root\s*\{/g, "$1\n:host{")
    .replace(/(^|[}\n])\s*html\s*\{/g, "$1\n:host{")
    .replace(/(^|[}\n])\s*body\s*\{/g, "$1\n:host{");
}

// The authored root font size, read from gazette.css's top-level `html` rule so
// both targets share one source of truth (the static target resolves `rem`
// against that rule directly). Falls back to 18 if the rule is ever reshaped.
function rootFontPx(gazetteCss) {
  const m = gazetteCss.match(/html\s*\{[^}]*?font-size:\s*([\d.]+)px/);
  return m ? m[1] : "18";
}

// Rewrite every `<n>rem` length to calc(<n> * var(--gz-rem)). Inside a shadow
// tree `rem` resolves against the HOST document's root font size, not :host, so
// a plain `:host{font-size}` cannot pin it; republishing the root size as
// --gz-rem and expressing each length against it does. Unlike a naive rem->em
// swap this does not compound through nested font-size changes, so a value like
// 2.2rem reproduces its standalone pixel size in any host. Safe for the
// --gz-rem name itself: the regex requires a digit immediately before `rem`,
// which `--gz-rem` never has.
function remToVar(css) {
  return css.replace(/(-?\d*\.?\d+)rem\b/g, "calc($1 * var(--gz-rem))");
}

// Build the combined shadow-root stylesheet text: theme tokens + structural
// CSS (both shadowified) + KaTeX. KaTeX's font URLs are relative to the katex
// css; the emitted fonts live under assets/katex/fonts/, so rewrite them to
// resolve against the shadow stylesheet's location.
export function buildShadowCss({ themeDir } = {}) {
  const tokensSrc =
    themeDir && fs.existsSync(path.join(themeDir, "tokens.css"))
      ? path.join(themeDir, "tokens.css")
      : VENDOR.tokensCss;
  const tokens = fs.readFileSync(tokensSrc, "utf8");
  const gazette = fs.readFileSync(VENDOR.gazetteCss, "utf8");
  const katexRaw = fs.readFileSync(path.join(VENDOR.katexDir, "katex.min.css"), "utf8");
  // Rewrite KaTeX's relative font URLs to the emitted assets/katex/fonts/, then
  // shadowify so its trailing `body{counter-reset:…}` (equation numbering) lands
  // on :host rather than a <body> that does not exist inside the shadow tree.
  const katex = shadowify(
    katexRaw.replace(/url\(\s*(['"]?)fonts\//g, "url($1assets/katex/fonts/")
  );

  const rootPx = rootFontPx(gazette);

  return [
    "/* gazette shadow-root styles — generated by the next target. */",
    "/* :root/html/body are rewritten to :host so the cascade starts at the",
    "   shadow host; rem lengths are rewritten to calc(n * var(--gz-rem)) so the",
    "   shadow tree keeps its own root size regardless of the host document; and",
    "   @font-face and KaTeX ship inline so the shadow tree is fully self-styled",
    "   and cannot leak into (or inherit from) the host app. */",
    `:host{--gz-rem:${rootPx}px;}`,
    remToVar(shadowify(tokens)),
    remToVar(shadowify(gazette)),
    remToVar(katex),
    // Figure breakout (.gazette-figure--wide) is surface-relative. In the shadow
    // tree the surface is the HOST element, not the embedding page's viewport, so
    // make :host a size-query container and bind the bleed unit to 1cqw (1% of the
    // host's inline size). This overrides the 1vw fallback in the structural rule
    // and keeps a wide figure inside its host wherever the embed is placed.
    ":host{container-type:inline-size;--gazette-bleed-unit:1cqw;}",
  ].join("\n");
}
